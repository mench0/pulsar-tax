package am.pulsar.tax.dto.enums;

/** Состояние банковской операции в учёте. */
public enum TransactionStatus {
    /** Тип предложен автоматически и ещё не подтверждён: в налог не попадает. */
    NEEDS_REVIEW,
    /** Пользователь подтвердил тип; для дохода и расхода созданы записи учёта. */
    CONFIRMED,
    /** Пользователь исключил операцию из учёта. */
    IGNORED
}
