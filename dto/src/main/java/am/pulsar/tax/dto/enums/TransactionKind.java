package am.pulsar.tax.dto.enums;

/**
 * Тип движения денег по счёту. Это не налоговая квалификация: налог считается только по подтверждённым
 * доходам (INCOME), а возврат покупателю (REFUND_ISSUED) требует решения пользователя.
 */
public enum TransactionKind {
    /** Поступление дохода от покупателя или заказчика. */
    INCOME,
    /** Оплата поставщику, аренда и прочие расходы. */
    EXPENSE,
    /** Перевод между своими счетами, конвертация валюты. */
    OWN_TRANSFER,
    /** Возврат денег нам: от поставщика, отмена покупки, кэшбэк. Не доход. */
    REFUND_RECEIVED,
    /** Возврат денег покупателю. */
    REFUND_ISSUED,
    /** Комиссия банка. */
    BANK_FEE,
    /** Уплата налогов и пошлин в бюджет. */
    TAX_PAYMENT,
    /** Прочая операция: нужна проверка. */
    OTHER
}
